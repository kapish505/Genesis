"""Hosted-agent source template.

The builder substitutes the marked placeholders and inlines the audited engine
from ``runtime/engine.py``. The generated file must import only names available
on Agentverse hosting: the Python standard library plus ``requests`` and
``uagents``/``uagents_core``. ``genesis.builder`` verifies that with an AST pass,
so this template can never quietly grow a disallowed import.

Runtime behaviour of a generated agent:

* every inbound ChatMessage is acknowledged first;
* a task message is either a JSON object of named inputs or free text, which is
  mapped to the spec's first text input (or ``{"text": ...}``);
* ``diff_state`` memory persists in ``ctx.storage`` when available;
* ``on_interval`` runs are enabled only for interval specs and report failures
  through the gateway's notify tool when one is configured.
"""

