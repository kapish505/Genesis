# --- task execution --------------------------------------------------------

def _inputs_from_message(text):
    declared = [item["name"] for item in SPEC.get("inputs", [])]
    stripped = text.strip()
    if stripped.startswith("{"):
        try:
            value = json.loads(stripped)
        except ValueError:
            value = None
        if isinstance(value, dict):
            inputs = {key: value[key] for key in declared if key in value}
            if inputs:
                return inputs
    if not declared:
        return {}
    first = SPEC["inputs"][0]
    if len(declared) == 1 or first["kind"] in {"url", "text"}:
        return {first["name"]: stripped}
    return {}


class Memory:
    """Persists diff_state across runs when ctx.storage supports dicts."""

    def __init__(self, ctx):
        self.ctx = ctx
        self.fallback = {}
        self.persistent = True

    def load(self):
        if not self.persistent:
            return dict(self.fallback)
        try:
            stored = self.ctx.storage.get("engine_state")
        except Exception:
            self.persistent = False
            return dict(self.fallback)
        if isinstance(stored, dict):
            return dict(stored)
        if isinstance(stored, str):
            try:
                value = json.loads(stored)
            except ValueError:
                return dict(self.fallback)
            return value if isinstance(value, dict) else dict(self.fallback)
        return dict(self.fallback)

    def save(self, state):
        self.fallback = dict(state)
        if not self.persistent:
            return
        try:
            self.ctx.storage.set("engine_state", state)
        except Exception:
            self.persistent = False


def execute(ctx, inputs):
    memory = Memory(ctx)
    state = memory.load()
    try:
        result = run_spec(SPEC, inputs, call_gateway, state)
    finally:
        memory.save(state)
    text = result["output"] if isinstance(result, dict) else str(result)
    if isinstance(result, dict) and result.get("errors"):
        text += "\\n\\n(some optional steps were skipped)"
    return text


def hosted_execute(ctx, inputs):
    return execute(ctx, inputs)


def _notify(ctx, text):
    if not NOTIFY_CHAT_ID:
        return
    try:
        call_gateway("notify", {"chat_id": NOTIFY_CHAT_ID, "text": text[:3500]})
    except Exception as exc:
        ctx.logger.warning("notification failed: %s", exc)


