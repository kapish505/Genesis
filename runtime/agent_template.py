# --- gateway client ---------------------------------------------------------

class GatewayCallError(RuntimeError):
    def __init__(self, message, retryable=False):
        super().__init__(message)
        self.retryable = retryable


def call_gateway(tool, args):
    url = GATEWAY_URL.rstrip("/") + "/" + tool
    headers = {"Authorization": "Bearer " + GATEWAY_TOKEN, "Content-Type": "application/json"}
    body = {"agent_id": AGENT_ID, "payload": args}
    last_error = None
    for attempt in range(3):
        try:
            response = requests.post(url, json=body, headers=headers, timeout=25)
        except requests.RequestException as exc:
            last_error = GatewayCallError("gateway unreachable: " + type(exc).__name__, True)
            time.sleep(1 + attempt)
            continue
        if response.status_code == 429 or response.status_code >= 500:
            last_error = GatewayCallError(
                "gateway returned HTTP " + str(response.status_code), True
            )
            time.sleep(1 + attempt)
            continue
        if response.status_code >= 400:
            detail = ""
            try:
                detail = str(response.json().get("detail", ""))
            except ValueError:
                detail = response.text[:200]
            raise GatewayCallError(
                "tool " + tool + " failed: " + detail, response.status_code == 429
            )
        try:
            return response.json()
        except ValueError as exc:
            raise GatewayCallError("gateway returned invalid JSON") from exc
    raise last_error or GatewayCallError("gateway call failed")


